export function detectLang() {
  const saved = localStorage.getItem("dash.lang");
  if (saved === "ru" || saved === "en") return saved;
  return (navigator.language || "ru").toLowerCase().startsWith("ru") ? "ru" : "ru";
}

let lang = detectLang();
export const getLang = () => lang;
export function setLang(next) {
  lang = next === "en" ? "en" : "ru";
  localStorage.setItem("dash.lang", lang);
  document.documentElement.lang = lang;
}

export function t(key, vars) {
  let text = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

export function settingLabel(key) {
  return SETTING_LABELS[lang][key] || key;
}

// Fill [data-i18n], [data-i18n-placeholder], [data-i18n-aria] in static markup.
export function translateStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}
